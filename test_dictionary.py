import json
import os


# ------------------------------------------------------------
# Путь к словарю
# ------------------------------------------------------------

DICT_FILE = r"D:\DialogysExplorer\dictionary\dialogys_dictionary.json"


# ------------------------------------------------------------
# Проверка существования файла
# ------------------------------------------------------------

if not os.path.exists(DICT_FILE):

    print("Файл словаря не найден:")
    print(DICT_FILE)

    input("\nНажмите Enter...")
    exit()


# ------------------------------------------------------------
# Загрузка JSON
# ------------------------------------------------------------

with open(
    DICT_FILE,
    "r",
    encoding="utf-8"
) as f:

    dictionary = json.load(f)


# ------------------------------------------------------------
# Статистика
# ------------------------------------------------------------

print()
print("=" * 60)
print("ПРОВЕРКА СЛОВАРЯ DIALOGYS")
print("=" * 60)

print()

print("Элементов :", len(dictionary["elements"]))
print("Операций  :", len(dictionary["operations"]))
print("Документов:", len(dictionary["titles"]))

print()


# ------------------------------------------------------------
# Первые элементы
# ------------------------------------------------------------

print("-" * 60)
print("Примеры элементов:")
print("-" * 60)

for i, item in enumerate(dictionary["elements"], start=1):

    print(f"{i}. {item}")

    if i >= 10:
        break


# ------------------------------------------------------------
# Первые операции
# ------------------------------------------------------------

print()
print("-" * 60)
print("Примеры операций:")
print("-" * 60)

for i, item in enumerate(dictionary["operations"], start=1):

    print(f"{i}. {item}")

    if i >= 10:
        break


# ------------------------------------------------------------
# Завершение
# ------------------------------------------------------------

print()
print("=" * 60)
print("Проверка завершена успешно.")
print("=" * 60)

input("\nНажмите Enter...")